_NAME_CHARS = set("abcdefghijklmnopqrstuvwxyz0123456789_")


def mentioned_tools(text, universe):
    """从一段提示词里挑出提到了哪些工具名。子串扫描 + 手判词边界,不引正则。

    词边界必须判:否则 `bash` 会在 `bash_exec` 里命中、`task_get` 会在
    `task_getx` 里命中。判法是看名字前后那一个字符在不在 [a-z0-9_] 里。
    """
    hits = set()
    for name in universe:
        start = 0
        while True:
            i = text.find(name, start)
            if i < 0:
                break
            start = i + 1
            before = text[i - 1] if i > 0 else ""
            after = text[i + len(name)] if i + len(name) < len(text) else ""
            if before in _NAME_CHARS or after in _NAME_CHARS:
                continue
            hits.add(name)
            break
    return hits


def check_prompts(role, text, owned, universe):
    """自检:该角色看到的提示词里点名的工具,必须真的在它手里。

    坏法最安静的一种:提示词教它调一个它没有的工具 —— 不报错、不抛异常,
    表现是「它怎么老说些做不到的事」,没人会想到是提示词抄了别的角色那一份。
    (9b37de0 修的就是这个:成员拿到了主agent那份「怎么组建团队」的说明,
     于是以为自己能建团队,还谎报「已启动成员」。)

    只查**一个方向**:提到了 → 必须拥有。
    反方向(拥有但没提)不算错,不报 —— 工具描述自己讲得清该怎么用,
    `task_get` 就从没在提示词里出现过,它照样能用。

    ★ 和 TOOLS.check_roles 同构:收「已知集合」、返回问题清单、**绝不抛异常**
      (提示词写错不该让整个项目起不来)。owned 是这个角色**能用的**工具,
      universe 是全部工具名(含 MCP)—— 两者都由调用方给,函数自己不找数据源。
    """
    missing = sorted(mentioned_tools(text, universe) - set(owned))
    if not missing:
        return []
    return [f"角色 {role} 的提示词里提到了它没有的工具 {missing} —— "
            f"它看不见这些工具(不在工具表里),只会照着提示词去调,然后撞回「不可用」"]
